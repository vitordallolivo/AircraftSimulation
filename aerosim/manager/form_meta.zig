/// o rótulo do campo (o próprio nome se não há)
pub fn label(name: []const u8) []const u8 {
    return labels.get(name) orelse name;
}

/// a unidade do campo ("" se não tem)
pub fn unit(name: []const u8) []const u8 {
    return units.get(name) orelse "";
}

/// a dica do campo ("" se não tem)
pub fn help(name: []const u8) []const u8 {
    return helps.get(name) orelse "";
}

/// as opções de um campo de texto que é uma escolha (`null`: texto livre)
pub fn choices(name: []const u8) ?[]const []const u8 {
    return choice_lists.get(name);
}

test "os rótulos e as unidades são os do Python" {
    try std.testing.expectEqualStrings("diedro", label("dihedral"));
    try std.testing.expectEqualStrings("°", unit("dihedral"));
    try std.testing.expectEqualStrings("m", unit("table_height"));
    try std.testing.expectEqualStrings("CLa", label("CLa"));
    try std.testing.expectEqual(@as(usize, 3), choices("layout").?.len);
    try std.testing.expect(choices("kind") == null);
}
